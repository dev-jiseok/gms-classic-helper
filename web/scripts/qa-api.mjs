import assert from 'node:assert/strict';
import { initialState } from '../lib/engine.mjs';
const origin=process.env.COMPASS_TEST_ORIGIN??'http://127.0.0.1:5187';
const anonymous=await fetch(`${origin}/api/state`);
assert.equal(anonymous.status,401,'anonymous state access must fail');
const signin=await fetch(`${origin}/signin-with-chatgpt?return_to=/`,{redirect:'manual'});
const cookie=signin.headers.getSetCookie().map(v=>v.split(';')[0]).join('; ');
assert.ok(cookie,'local development auth cookie missing');
const headers={Cookie:cookie,'Content-Type':'application/json',Origin:origin};
const read=async()=>{const r=await fetch(`${origin}/api/state`,{headers});assert.equal(r.status,200);return r.json();};
const prior=await read();
const state=prior.state??initialState();
const write=await fetch(`${origin}/api/state`,{method:'PUT',headers,body:JSON.stringify({state:{...state,qaMarker:true},revision:prior.revision})});
assert.equal(write.status,200,await write.text());
const stored=await read();assert.equal(stored.state.qaMarker,true);
const stale=await fetch(`${origin}/api/state`,{method:'PUT',headers,body:JSON.stringify({state,revision:prior.revision})});
assert.equal(stale.status,409,'stale saves must not overwrite newer state');
const crossOrigin=await fetch(`${origin}/api/state`,{method:'PUT',headers:{...headers,Origin:'https://elsewhere.invalid'},body:JSON.stringify({state,revision:stored.revision})});
assert.equal(crossOrigin.status,403);
const restored=await fetch(`${origin}/api/state`,{method:'PUT',headers,body:JSON.stringify({state,revision:stored.revision})});assert.equal(restored.status,200);
const post=await fetch(`${origin}/api/posts`,{method:'POST',headers,body:JSON.stringify({room:'our-party',kind:'party',author:'개발 검증',payload:{title:'검증용 게시물',capacity:4}})});
assert.equal(post.status,200,await post.clone().text());const created=await post.json();
const invalid=await fetch(`${origin}/api/posts`,{method:'POST',headers,body:JSON.stringify({kind:'unknown',payload:{title:'test'}})});assert.equal(invalid.status,400);
const close=await fetch(`${origin}/api/posts`,{method:'POST',headers,body:JSON.stringify({action:'close',id:created.post.id})});assert.equal(close.status,200);
console.log(JSON.stringify({anonymousDenied:true,authenticatedReadWrite:true,staleRevisionBlocked:true,crossOriginWriteBlocked:true,postCreateAndClose:true,invalidPostRejected:true}));
